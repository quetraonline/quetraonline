-- Nowa Chat Tracker database setup.
-- Run this file in the Supabase SQL editor. Secret hashes are inserted separately
-- by the setup process; never commit raw credentials to Git.

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  game_time_text text,
  player text not null default 'Bilinmiyor',
  message text not null,
  matched_keywords text[] not null default '{}',
  source text not null default 'ldplayer-ocr',
  dedupe_hash text not null unique
);

create index if not exists chat_messages_created_at_idx on public.chat_messages (created_at desc);
create index if not exists chat_messages_player_idx on public.chat_messages (player);
create index if not exists chat_messages_keywords_idx on public.chat_messages using gin (matched_keywords);
alter table public.chat_messages enable row level security;

create schema if not exists tracker_private;
revoke all on schema tracker_private from public, anon, authenticated;

create table if not exists tracker_private.credentials (
  name text primary key,
  secret_hash bytea not null,
  updated_at timestamptz not null default now()
);
revoke all on tracker_private.credentials from public, anon, authenticated;

create or replace function public.tracker_insert_message(
  p_ingest_token text,
  p_player text,
  p_message text,
  p_matched_keywords text[],
  p_game_time_text text,
  p_dedupe_hash text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, tracker_private, extensions
as $$
declare
  v_expected bytea;
  v_inserted integer;
begin
  select secret_hash into v_expected from tracker_private.credentials where name = 'ingest_token';
  if v_expected is null or extensions.digest(convert_to(coalesce(p_ingest_token, ''), 'UTF8'), 'sha256') is distinct from v_expected then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  if coalesce(trim(p_message), '') = '' then
    raise exception 'message is required' using errcode = '22023';
  end if;
  insert into public.chat_messages (player, message, matched_keywords, game_time_text, source, dedupe_hash)
  values (coalesce(nullif(trim(p_player), ''), 'Bilinmiyor'), left(trim(p_message), 1000), coalesce(p_matched_keywords[1:20], '{}'::text[]), left(p_game_time_text, 80), 'ldplayer-ocr', p_dedupe_hash)
  on conflict (dedupe_hash) do nothing;
  get diagnostics v_inserted = row_count;
  return v_inserted > 0;
end;
$$;

create or replace function public.tracker_get_messages(
  p_session_secret text,
  p_start timestamptz default null,
  p_end timestamptz default null,
  p_keyword text default null,
  p_player text default null
)
returns table (id bigint, created_at timestamptz, game_time_text text, player text, message text, matched_keywords text[], source text)
language plpgsql
security definer
set search_path = pg_catalog, public, tracker_private, extensions
as $$
declare
  v_expected bytea;
begin
  select secret_hash into v_expected from tracker_private.credentials where name = 'dashboard_session';
  if v_expected is null or extensions.digest(convert_to(coalesce(p_session_secret, ''), 'UTF8'), 'sha256') is distinct from v_expected then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  return query
  select m.id, m.created_at, m.game_time_text, m.player, m.message, m.matched_keywords, m.source
  from public.chat_messages m
  where (p_start is null or m.created_at >= p_start)
    and (p_end is null or m.created_at < p_end)
    and (p_keyword is null or m.message ilike '%' || replace(replace(p_keyword, '%', ''), '_', '') || '%')
    and (p_player is null or m.player ilike '%' || replace(replace(p_player, '%', ''), '_', '') || '%')
  order by m.created_at desc limit 1000;
end;
$$;

create or replace function public.tracker_get_stats(
  p_session_secret text,
  p_start timestamptz default null,
  p_end timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, tracker_private, extensions
as $$
declare
  v_expected bytea;
  v_result jsonb;
begin
  select secret_hash into v_expected from tracker_private.credentials where name = 'dashboard_session';
  if v_expected is null or extensions.digest(convert_to(coalesce(p_session_secret, ''), 'UTF8'), 'sha256') is distinct from v_expected then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  with base as (
    select m.player, m.created_at from public.chat_messages m
    where (p_start is null or m.created_at >= p_start)
      and (p_end is null or m.created_at < p_end)
  ),
  player_counts as (
    select coalesce(nullif(player, ''), 'Bilinmiyor') as name, count(*)::bigint as count
    from base group by 1 order by count desc, name asc limit 20
  )
  select jsonb_build_object(
    'total', (select count(*) from base),
    'players', coalesce((select jsonb_agg(jsonb_build_object('name', name, 'count', count) order by count desc, name asc) from player_counts), '[]'::jsonb),
    'active_players', (select count(distinct player) from base),
    'last_message_at', (select max(created_at) from base)
  ) into v_result;
  return v_result;
end;
$$;

revoke all on function public.tracker_insert_message(text, text, text, text[], text, text) from public;
revoke all on function public.tracker_get_messages(text, timestamptz, timestamptz, text, text) from public;
revoke all on function public.tracker_get_stats(text, timestamptz, timestamptz) from public;
grant execute on function public.tracker_insert_message(text, text, text, text[], text, text) to anon;
grant execute on function public.tracker_get_messages(text, timestamptz, timestamptz, text, text) to anon;
grant execute on function public.tracker_get_stats(text, timestamptz, timestamptz) to anon;
